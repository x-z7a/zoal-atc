#!/usr/bin/env python3
"""Write src/models/model_manifest.inc: every file of the two models the plugin
runs, with its size, its SHA-256 and the pinned URL the plugin fetches it from
when it is missing or out of date.

The source of truth is the tree scripts/ensure-models.sh provisions and
checksums. Each file is matched against the HuggingFace repository at a pinned
commit, by its git blob id or, for an LFS file, by its SHA-256, so a URL in the
manifest is never one that serves different bytes than the release ships.

    scripts/ensure-models.sh && scripts/model-manifest.py

Regenerate whenever ensure-models.sh moves a pin.
"""

import hashlib
import json
import os
import subprocess
import sys
import urllib.parse

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODELS = os.environ.get("ZOAL_ATC_MODELS", os.path.join(REPO_ROOT, ".cache", "models"))
OUT = os.path.join(REPO_ROOT, "src", "models", "model_manifest.inc")

# name, the plugin's path under models/, HuggingFace repo, pinned commit, the
# path inside the repo (a file, or a directory whose files are all taken).
SOURCES = [
    ("stt", "ggml-small.en-q5_1.bin", "ggerganov/whisper.cpp",
     "5359861c739e955e79d9a303bcbc70fb988958b1", "ggml-small.en-q5_1.bin"),
    ("tts", "kokoro-multi-lang-v1_0", "csukuangfj/kokoro-multi-lang-v1_0",
     "f7b96bb6bef5c5da4d3aa4f4e0498fbbf62dc78b", ""),
]

# Files the plugin appends to after they are installed: prepare_catalogue
# gives model.onnx its speaker count. Only the first `size` bytes are checked.
APPENDABLE = {"kokoro-multi-lang-v1_0/model.onnx"}


def hf_tree(repo, commit):
    url = "https://huggingface.co/api/models/%s/tree/%s?recursive=1" % (repo, commit)
    # curl rather than urllib: a python.org Python has no CA bundle on macOS.
    listing = subprocess.run(["curl", "-fsSL", url], check=True, capture_output=True).stdout
    return {e["path"]: e for e in json.loads(listing) if e["type"] == "file"}


def local_files(path):
    if os.path.isfile(path):
        return [("", path)]
    out = []
    for root, _, files in os.walk(path):
        for name in files:
            if name.startswith(".content-sha256"):
                continue
            full = os.path.join(root, name)
            out.append((os.path.relpath(full, path).replace(os.sep, "/"), full))
    return sorted(out)


def main():
    entries = []
    for model, local, repo, commit, remote in SOURCES:
        tree = hf_tree(repo, commit)
        base = os.path.join(MODELS, local)
        if not os.path.exists(base):
            sys.exit("%s is missing: run scripts/ensure-models.sh first" % base)
        for rel, full in local_files(base):
            data = open(full, "rb").read()
            sha256 = hashlib.sha256(data).hexdigest()
            remote_path = remote if rel == "" else rel
            entry = tree.get(remote_path)
            if entry is None:
                sys.exit("%s@%s has no %s" % (repo, commit, remote_path))
            if entry.get("lfs"):
                same = entry["lfs"]["oid"] == sha256
            else:
                blob = b"blob %d\0" % len(data) + data
                same = entry["oid"] == hashlib.sha1(blob).hexdigest()
            if not same:
                sys.exit("%s@%s serves a different %s" % (repo, commit, remote_path))
            path = local if rel == "" else local + "/" + rel
            # Percent-encoded: espeak-ng-data/voices/!v/Mr serious has a space.
            url = "https://huggingface.co/%s/resolve/%s/%s" % (
                repo, commit, urllib.parse.quote(remote_path, safe="/"))
            entries.append((model, path, len(data), sha256, url, path in APPENDABLE))

    with open(OUT, "w", newline="\n") as out:
        out.write("// Generated by scripts/model-manifest.py. Do not edit.\n")
        out.write("// {model, path under models/, size, sha256, url, appendable}\n")
        for model, path, size, sha256, url, appendable in entries:
            out.write('{"%s", "%s", %dULL, "%s", "%s", %s},\n'
                      % (model, path, size, sha256, url, "true" if appendable else "false"))
    print("wrote %d files to %s" % (len(entries), OUT))


if __name__ == "__main__":
    main()
